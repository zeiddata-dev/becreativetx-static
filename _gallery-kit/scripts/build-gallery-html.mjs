// Writes the gallery tiles into case-studies.html as static markup.
//
// The page must work with JavaScript disabled, so the tiles ship in the HTML
// rather than being built at runtime. js/gallery.js then reads the DOM and
// layers filtering and the lightbox on top of markup that already works.
//
// Source of truth is js/gallery-data.js. Re-run after editing it.
//
// Run: node scripts/build-gallery-html.mjs

import { readFile, writeFile } from 'node:fs/promises';

// Target page. Defaults to the live-look gallery; pass a path to override.
const PAGE = process.argv[2] ?? 'becreativetx-site/casestudies.html';
const DATA = 'becreativetx-site/js/gallery-data.js';

const START = '<!-- BEGIN gallery-tiles : generated by scripts/build-gallery-html.mjs -->';
const END = '<!-- END gallery-tiles -->';

function esc(s) {
  return String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

// Evaluate the data file in a bare context to read the array without a parser.
async function loadItems() {
  const src = await readFile(DATA, 'utf8');
  const scope = { window: {} };
  new Function('window', src)(scope.window);
  return scope.window.GALLERY_ITEMS ?? [];
}

const items = await loadItems();

if (items.length === 0) {
  console.error('FAIL: no items in', DATA);
  process.exit(1);
}

const tiles = items
  .map((it, i) => {
    const cap = it.client || 'be creative';
    const loading = i < 3 ? 'eager' : 'lazy';
    return `      <li class="gal-item" data-cat="${esc(it.cat)}" data-id="${esc(it.id)}" data-client="${esc(cap)}">
        <button type="button" class="gal-tile" aria-label="View larger: ${esc(it.alt)}">
          <span class="frame"><img src="assets/gallery/thumb/${esc(it.id)}.webp" alt="${esc(it.alt)}" loading="${loading}" decoding="async" width="800" height="800"></span>
          <span class="gal-caption">${esc(cap)}</span>
        </button>
      </li>`;
  })
  .join('\n');

const block = `${START}
    <ul class="gal-grid" id="gallery-grid">
${tiles}
    </ul>
    ${END}`;

const page = await readFile(PAGE, 'utf8');

if (!page.includes(START) || !page.includes(END)) {
  console.error(`FAIL: markers not found in ${PAGE}. Expected:\n  ${START}\n  ${END}`);
  process.exit(1);
}

const next = page.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), block);

await writeFile(PAGE, next, 'utf8');

const byCat = items.reduce((acc, it) => ({ ...acc, [it.cat]: (acc[it.cat] ?? 0) + 1 }), {});

console.log(`wrote ${items.length} tiles into ${PAGE}`);
console.table(byCat);
console.log('RESULT=PASS');
